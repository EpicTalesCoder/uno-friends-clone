export function loadSaveState() {
  const def = createDefaultSave();
  try {
    if (typeof localStorage === 'undefined') return def;
    const raw = localStorage.getItem(STORAGE_SAVE_KEY);
    if (!raw) return def;
    const parsed = JSON.parse(raw);
    return {
      ...def,
      ...parsed,
      stats: { ...def.stats, ...(parsed.stats || {}) },
    };
  } catch {
    return def;
  }
}

export function persistSaveState(save) {
  try {
    if (typeof localStorage === 'undefined') return;
    localStorage.setItem(STORAGE_SAVE_KEY, JSON.stringify(save));
  } catch {
    // ignore quota errors
  }
}

export function resetSaveState() {
  const def = createDefaultSave();
  persistSaveState(def);
  return def;
}

export function getTotalStars(save) {
  let sum = 0;
  for (const row of save.stageStars) {
    for (const s of row) sum += s | 0;
  }
  return sum;
}

